"""Демо: SRM (Sample Ratio Mismatch) — санити-чек соотношения групп."""
import numpy as np
from scipy import stats
import streamlit as st

st.title("🔀 SRM-чек (Sample Ratio Mismatch)")
st.caption("Блок 3 · Модуль 3.3 — сломан ли сплиттер до того, как поверить результатам.")

st.markdown(
    """
Вы ожидаете сплит, например, 50/50. Если фактическое соотношение значимо отличается от ожидаемого —
это **SRM**: где-то баг (сплиттер, логирование, фильтрация ботов, редиректы). При SRM результатам
теста **верить нельзя** — сначала чинят причину, а не «поправляют анализ».

Проверка — критерий **χ²** на соответствие ожидаемым долям.
    """
)

c = st.columns(4)
nA = c[0].number_input("Пользователей в A", value=50120, min_value=1)
nB = c[1].number_input("Пользователей в B", value=49880, min_value=1)
ratio_a = c[2].slider("Ожидаемая доля A, %", 10, 90, 50) / 100
alpha = c[3].select_slider("Порог α", [0.001, 0.01, 0.05], 0.001,
                           help="Для SRM обычно берут строгий порог, напр. 0.001.")

total = nA + nB
expected = np.array([total * ratio_a, total * (1 - ratio_a)])
observed = np.array([nA, nB])
chi2, p = stats.chisquare(observed, expected)

obs_ratio = nA / total
c1, c2, c3 = st.columns(3)
c1.metric("Ожидаемо A", f"{ratio_a:.1%}")
c2.metric("Фактически A", f"{obs_ratio:.2%}", delta=f"{(obs_ratio-ratio_a)*100:+.2f} п.п.")
c3.metric("p-value (χ²)", f"{p:.2e}")

if p < alpha:
    st.error(
        f"🚨 SRM ОБНАРУЖЕН (p={p:.2e} < {alpha}). Соотношение групп не соответствует ожидаемому. "
        "НЕ интерпретируйте метрики эксперимента — ищите баг в назначении/логировании/фильтрации.",
        icon="🚨")
else:
    st.success(
        f"✅ SRM не обнаружен (p={p:.3f} ≥ {alpha}). Соотношение групп в пределах случайных колебаний — "
        "можно переходить к анализу метрик.", icon="✅")

with st.expander("💡 Частые причины SRM"):
    st.markdown(
        "- Разная фильтрация ботов/выбросов в группах.\n"
        "- Редиректы/задержки загрузки варианта B (часть юзеров «отваливается»).\n"
        "- Ошибка в хеш-функции распределения или переопределение групп.\n"
        "- Разное окно логирования / джойны, теряющие часть событий одной группы."
    )
st.caption("Практика Модуля 3.3: этот чек стоит запускать автоматически до любого анализа результатов.")
